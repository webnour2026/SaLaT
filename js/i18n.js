let lang = 'fr';
export const LOCALES = { fr: 'fr-FR', ar: 'ar-MA', en: 'en-GB' };

export function setLang(l) {
  lang = DICT[l] ? l : 'fr';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
}
export const getLang = () => lang;
export const locale = () => `${LOCALES[lang]}-u-nu-latn`;
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.fr[key] ?? key;
  if (vars && typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
